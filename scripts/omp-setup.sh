#!/usr/bin/env bash
# omp-setup.sh — point omp (oh-my-pi) at this rig's local models, through the
# LiteLLM gateway, with the settings a local GPU needs.
#
#   bash scripts/omp-setup.sh            # write/refresh the `club` provider, print the next steps
#   bash scripts/omp-setup.sh --print    # show the provider block, change nothing
#   bash scripts/omp-setup.sh --gateway http://gateway-host:4000/v1   # a gateway on another box
#   bash scripts/omp-setup.sh --auto-switching   # also install the live alias: the
#     club-live extension plus its club-live.json settings (see below)
#
# WHAT IT WRITES — one marked block in ~/.omp/agent/models.yml (or
# $PI_CODING_AGENT_DIR/models.yml): a `club` provider on the LiteLLM gateway
# (:4000) with `discovery: litellm`. The gateway's route set is re-rendered from
# whatever is actually serving on every switch.sh (scripts/lib/litellm-sync.sh),
# and each route carries model_info, so omp sees the live model with its REAL
# context window and output cap — no hand-kept model list, no edit on a switch.
# Other providers in the file are never touched; the old file is backed up.
#
# WHAT IT DOES NOT WRITE — your config.yml. Runtime settings (effort per role,
# append-only context, compaction, artifact spill, subagent concurrency, stream
# timeouts) ship as an overlay, services/omp/omp-club.yml, that you load per run:
#     omp --config <repo>/services/omp/omp-club.yml
# so your own roles and settings stay as they are. docs/CODING_AGENTS.md explains
# every setting and which slug to serve for agent work.
# The one exception: --auto-switching installs the live alias — it copies the
# club-live extension into the agent dir and writes its settings beside it
# (extensions/club-live.json). config.yml stays yours: the flag PRINTS the
# modelRoles block to paste. Re-run it after a gateway-key rotate.
#
# THE KEY — the gateway's LITELLM_MASTER_KEY from your club-3090 settings
# (~/.config/club-3090/secrets.env; `bash scripts/gateway-key.sh rotate` makes one),
# else the public default every install shares. LITELLM_MASTER_KEY set in the shell
# wins (a gateway on another box). After a rotate, re-run this script.
set -euo pipefail
export PYTHONUTF8="${PYTHONUTF8:-1}"
ROOT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"

PRINT=0
AUTO=0
GATEWAY="http://127.0.0.1:4000/v1"
while [[ $# -gt 0 ]]; do
  case "$1" in
    --print) PRINT=1; shift ;;
    --gateway) GATEWAY="${2:?--gateway needs a URL}"; shift 2 ;;
    --auto-switching) AUTO=1; shift ;;
    -h|--help) sed -n '2,33p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "omp-setup: unknown argument '$1' (see --help)" >&2; exit 2 ;;
  esac
done

AGENT_DIR="${PI_CODING_AGENT_DIR:-$HOME/.omp/agent}"
MODELS_YML="$AGENT_DIR/models.yml"
# The key through the one settings loader (#1466, #1467) — never read out of the
# compose file, whose line is `${LITELLM_MASTER_KEY:-…}` now, not the key.
# shellcheck source=lib/club-config.sh
. "$ROOT_DIR/scripts/lib/club-config.sh"
KEY="$(club_config_get LITELLM_MASTER_KEY "$ROOT_DIR" || true)"
KEY="${KEY:-sk-litellm-master-key}"   # the compose's default, when nothing is stored

python3 - "$MODELS_YML" "$GATEWAY" "$KEY" "$PRINT" "$AUTO" "$AGENT_DIR/extensions" "$ROOT_DIR" <<'PY'
import datetime, io, json, os, re, sys

path, gateway, key, print_only = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4] == "1"
auto, ext_dir, root = sys.argv[5] == "1", sys.argv[6], sys.argv[7]
BEGIN = "  # >>> club-3090 local models (generated by club-3090 scripts/omp-setup.sh; re-run to refresh) >>>"
END = "  # <<< club-3090 local models <<<"

# Qwen3.8-family served ids (what the engine's own /v1/models says, not the
# registry's model name). Their chat template takes `reasoning_effort`
# (low | medium | xhigh; it DEFAULTS to xhigh when a request names none) — so omp
# must send the effort on every role; qwenTemplateReasoningEffort puts it in
# chat_template_kwargs, where both vLLM and SGLang pass it to the template.
# Qwen3.8 slugs all serve the shared id `qwen3.8-27b`; the ThinkingCap slugs are
# replicas that serve their OWN name `thinkingcap38-27b` on every tier (fast /
# max / superfast, vLLM and SGLang).
# The FP8 tiers also serve a `-fp8` alias, and the gateway lists every alias as its
# own route, so each needs the override too. test-omp-setup checks this list
# against every name the Qwen3.8-family composes serve.
QWEN38_IDS = ["qwen3.8-27b", "qwen3.8-27b-fp8", "qwen3.8-27b-swift15", "thinkingcap38-27b", "thinkingcap38-27b-fp8"]

def qwen38_override(mid: str, fam: dict) -> str:
    summary = "          supportsReasoningSummary: false\n" if fam["compat"].get("supportsReasoningSummary") is False else ""
    return f"""      {mid}:
        # Reply cap (thinking + answer). The gateway reports it per route, but when
        # it can't (routes rendered before model_info existed, or an engine that
        # reports no context) omp falls back to its catalog's 65,536 — the WHOLE
        # window of the 65K single-card slug. Pinned here, it wins over discovery;
        # 32768 is at most half the window on every Qwen3.8 slug.
        maxTokens: {fam["maxTokens"]}
        # A thinking model on every engine. Stated here because the gateway only
        # says so for slugs that declare a thinking sampler profile; without it omp
        # treats the model as non-reasoning and never sends an effort at all.
        reasoning: true
        thinking:
          mode: effort
          efforts: [{", ".join(fam["ladder"]["efforts"])}]
          defaultLevel: {fam["ladder"]["defaultLevel"]}
        compat:
          supportsReasoningEffort: true
          qwenTemplateReasoningEffort: true
{summary}          # Chat-completions wire only (omp talks Responses to an `openai/` gateway
          # route and does not send it there). vLLM enforces it on the THINKING
          # field, not the reply — keep it generous; effort is the lever. SGLang
          # ignores it.
          extraBody:
            thinking_token_budget: {fam["compat"]["extraBody"]["thinking_token_budget"]}
"""

# Qwen3.8-Flash-Next takes the same template effort (low | medium | xhigh, xhigh
# when a request names none), so its ids get the Qwen3.8 override. GLM-5.3-Flash
# has its own ladder (below). Without an override omp treats a model as
# non-reasoning, because no Flash-Next or GLM slug declares a thinking sampler
# profile for the gateway to report, so it sent NO effort at all and every request
# ran at the server's default, the slowest rung (club-3090 Discussion #1690).
# These are the ids the engines REPORT, which is what the gateway names each route:
# a compose's --served-model-name / --alias / --model-name / SERVED_MODEL_NAME / --served-name (QEngine),
# Strata's "<family name>-<quant>" (qwen3.8-flash-next-iq3_s, swift-1.5-iq3_s) and
# Project Maya's model_name (glm-5.3-flash). test-omp-setup checks both lists
# against the composes.
# Sent with the Flash-Next and GLM overrides only. omp adds `summary: "auto"` to the
# Responses `reasoning` object, and LiteLLM's Responses -> chat-completions bridge
# (routes on engines without /v1/responses: tabbyAPI, Project Maya) then forwards the
# WHOLE object as `reasoning_effort` ({"effort": "low", "summary": "auto"}), which
# tabbyAPI's string field and Maya's effort parser both reject. Without the summary
# the bridge sends the effort string. The engines that serve Responses themselves
# (llama.cpp, Strata, vLLM) don't use the summary request.
FLASH_NEXT_IDS = ["qwen3.8-flash-next", "qwen3.8-flash-next-ple", "qwen3.8-flash-next-swift15",
                  "qwen3.8-flash-next-exl3-3.05bpw", "qwen3.8-flash-next-exl3-4.05bpw",
                  "qwen3.8-flash-next-iq3_s", "swift-1.5-iq3_s"]
GLM53_IDS = ["glm-5.3-flash"]

# The per-family wire shape — the SINGLE source for both the modelOverrides
# written into models.yml and the families list written into
# extensions/club-live.json for the club-live extension (--auto-switching).
# The alias and the `club` provider cannot drift: one list, two renderings.
# supportsReasoningSummary: false rides the Flash-Next and GLM families only —
# omp adds `summary: "auto"` to the Responses `reasoning` object, and LiteLLM's
# Responses -> chat-completions bridge (routes on engines without /v1/responses:
# tabbyAPI, Project Maya) forwards the WHOLE object as `reasoning_effort`
# ({"effort": "low", "summary": "auto"}), which tabbyAPI's string field and
# Maya's effort parser both reject. The engines that serve Responses themselves
# (llama.cpp, Strata, vLLM) don't use the summary request.
FAMILIES = [
    {"name": "qwen38", "ids": QWEN38_IDS,
     "ladder": {"efforts": ["low", "medium", "xhigh"], "defaultLevel": "medium"},
     "maxTokens": 32768,
     "compat": {"supportsReasoningEffort": True, "qwenTemplateReasoningEffort": True,
                "extraBody": {"thinking_token_budget": 8192}}},
    {"name": "flash-next", "ids": FLASH_NEXT_IDS,
     "ladder": {"efforts": ["low", "medium", "xhigh"], "defaultLevel": "medium"},
     "maxTokens": 32768,
     "compat": {"supportsReasoningEffort": True, "qwenTemplateReasoningEffort": True,
                "supportsReasoningSummary": False,
                "extraBody": {"thinking_token_budget": 8192}}},
    {"name": "glm53", "ids": GLM53_IDS,
     "ladder": {"efforts": ["low", "high", "max"], "defaultLevel": "max"},
     "maxTokens": 32768,
     "compat": {"supportsReasoningEffort": True, "qwenTemplateReasoningEffort": True,
                "supportsReasoningSummary": False}},
]

def glm53_override(mid: str, fam: dict) -> str:
    return f"""      {mid}:
        # Reply cap, as for Qwen3.8; GLM's windows are 131K (Project Maya) to 205K.
        maxTokens: {fam["maxTokens"]}
        reasoning: true
        # GLM-5.3-Flash's own ladder: max (the vendor's default and the composes'),
        # high and low. It cannot turn thinking off, low is the near-zero end, and
        # `medium` is not one of its levels, so omp only offers these three. The
        # default stays max, what the servers already do when a request names none.
        thinking:
          mode: effort
          efforts: [{", ".join(fam["ladder"]["efforts"])}]
          defaultLevel: {fam["ladder"]["defaultLevel"]}
        compat:
          supportsReasoningEffort: {str(fam["compat"]["supportsReasoningEffort"]).lower()}
          # The chat-completions form, chat_template_kwargs.reasoning_effort: llama.cpp
          # and Project Maya read it as well as the top-level field.
          qwenTemplateReasoningEffort: {str(fam["compat"]["qwenTemplateReasoningEffort"]).lower()}
          supportsReasoningSummary: {str(fam["compat"]["supportsReasoningSummary"]).lower()}
"""

block = f"""{BEGIN}
  club:
    baseUrl: {gateway}
    apiKey: {key}
    api: openai-completions
    discovery:
      # Reads LiteLLM's /model_group/info: the live model list plus each route's
      # model_info (max_input_tokens, max_output_tokens, capabilities), which
      # scripts/lib/litellm-sync.sh renders from the serving engine on every switch.
      type: litellm
    compat:
      supportsDeveloperRole: false
      # Thinking on/off rides chat_template_kwargs.enable_thinking — the field vLLM,
      # SGLang and llama.cpp all read. (`qwen` would send a top-level enable_thinking
      # that vLLM and SGLang ignore, so omp's "off" level would silently keep thinking on.)
      thinkingFormat: qwen-chat-template
      # ...on chat completions. Through the gateway omp talks the Responses API
      # (`discovery: litellm`), where "off" used to send no `reasoning` field at all,
      # so the template's default (thinking on) still ran. This makes it send
      # `reasoning: {{effort: "none"}}`, which vLLM and SGLang both serve with no
      # reasoning. Upstream's answer to oh-my-pi#11184; checked through the gateway.
      reasoningDisableMode: none-effort
    modelOverrides:
{"".join(qwen38_override(m, FAMILIES[0]) for m in FAMILIES[0]["ids"])}{"".join(qwen38_override(m, FAMILIES[1]) for m in FAMILIES[1]["ids"])}{"".join(glm53_override(m, FAMILIES[2]) for m in FAMILIES[2]["ids"])}{END}
"""

if print_only:
    print("providers:")
    print(block, end="")
    sys.exit(0)

os.makedirs(os.path.dirname(path), exist_ok=True)
text = io.open(path, encoding="utf-8").read() if os.path.exists(path) else ""
if BEGIN.strip() in text and END.strip() in text:
    pre, rest = text.split(BEGIN.strip(), 1)
    _, post = rest.split(END.strip(), 1)
    pre = pre.rstrip(" ")               # drop the old marker line's own indent
    new = pre + block + post.lstrip("\n")
    action = "refreshed"
elif re.search(r"^\s+club:\s*$", text, re.M) and BEGIN.strip() not in text:
    sys.exit("[omp-setup] models.yml already has a hand-written `club:` provider — "
             "rename or remove it, then re-run (this script only manages its own marked block).")
elif not text.strip():
    new = "providers:\n" + block
    action = "created"
elif re.search(r"^providers:\s*$", text, re.M):
    # models.yml's root holds only `providers:`, so the block can be appended at
    # the end of the file and still sit inside that mapping.
    new = text.rstrip("\n") + "\n" + block
    action = "added"
else:
    sys.exit("[omp-setup] models.yml has no top-level `providers:` key — not touching it.")

if text:                                # back up only when we are about to write
    stamp = datetime.datetime.now().strftime("%Y%m%d-%H%M%S")
    io.open(f"{path}.bak-{stamp}", "w", encoding="utf-8").write(text)
    print(f"[omp-setup] backed up {path} -> {path}.bak-{stamp}")
tmp = path + ".tmp"
io.open(tmp, "w", encoding="utf-8").write(new)
os.replace(tmp, path)
print(f"[omp-setup] {action} the `club` provider in {path}")

if auto:
    # The club-live extension's settings — one small JSON file next to the
    # installed extension, the single place the extension gets its config.
    # renderedCfg is the file the RUNNING litellm container actually mounts
    # (mounted_runtime_path(); a worktree setup's file can live outside this
    # checkout), falling back to this checkout's rendered view. The key comes
    # from the club_config loader above — the extension never re-implements
    # that precedence; a rotate means re-running this script, as for `club`.
    # families is the same FAMILIES list the modelOverrides above are built from.
    sys.path.insert(0, os.path.join(root, "scripts", "lib"))
    rendered = None
    try:
        from litellm_sync import mounted_runtime_path
        rendered = mounted_runtime_path()
    except Exception:
        pass
    if not rendered:
        rendered = os.path.join(root, "services", "litellm", "config.runtime.yaml")
    gw = gateway.rstrip("/")
    if gw.endswith("/v1"):
        gw = gw[:-len("/v1")]
    settings = {"generatedBy": "club-3090 scripts/omp-setup.sh --auto-switching",
                "renderedCfg": rendered, "gateway": gw, "key": key,
                "families": FAMILIES}
    os.makedirs(ext_dir, exist_ok=True)
    jpath = os.path.join(ext_dir, "club-live.json")
    jtmp = jpath + ".tmp"
    io.open(jtmp, "w", encoding="utf-8").write(json.dumps(settings, indent=2) + "\n")
    os.chmod(jtmp, 0o600)          # the gateway key sits in it: the tmp never
    os.replace(jtmp, jpath)        # lands world-readable, not even briefly
    print(f"[omp-setup] wrote the club-live settings -> {jpath}")
PY

[[ $PRINT -eq 1 ]] && exit 0

STEP4=""
if [[ $AUTO -eq 1 ]]; then
  mkdir -p "$AGENT_DIR/extensions"
  cp "$ROOT_DIR/services/omp/extensions/club-live.ts" "$AGENT_DIR/extensions/club-live.ts"
  echo "[omp-setup] installed the club-live extension -> $AGENT_DIR/extensions/club-live.ts"
  STEP4="  4. Live alias: INSTALLED —
         extension: $AGENT_DIR/extensions/club-live.ts
         settings:  $AGENT_DIR/extensions/club-live.json — the rendered config
                    the gateway mounts, the gateway URL and key, and the
                    per-family wire settings (generated from the same lists as
                    the modelOverrides above, so alias and provider cannot
                    drift). Re-run --auto-switching after a gateway-key rotate
                    or a --gateway change; the extension picks it up on its
                    next refresh, no omp restart.
       config.yml stays yours — paste the roles in yourself:

         modelRoles:
           default: club-live/live:medium
           plan: club-live/live:xhigh
           slow: club-live/live:xhigh
           task: club-live/live:low
           smol: club-live/live:low
           tiny: club-live/live:low
           commit: club-live/live:low

       If config.yml has an enabledModels list, add club-live/* to it — an
       allow-list without the alias degrades these roles with only a startup
       warning.
       Effort suffixes clamp to the SERVING family's ladder: on GLM
       (low/high/max) a :medium role runs at low and :xhigh at high — the
       nearest lower rung goes on the wire; never an error, never an effort
       the serving engine has never heard of."
else
  STEP4="  4. Optional, recommended — keep roles pointed at whatever is serving, across
     every switch.sh and inside running sessions:
                      bash \"$ROOT_DIR/scripts/omp-setup.sh\" --auto-switching
     (installs the extension + its club-live.json settings and prints the
     modelRoles block to paste; docs/CODING_AGENTS.md, \"The live alias\")."
fi

cat <<EOF

Next:
  1. Serve a model:   bash scripts/switch.sh --force vllm/qwen38-27b-dual-fast   (experimental; the slug docs/CODING_AGENTS.md recommends for agents)
  2. Check omp sees it with its real context window:
                      omp models club
  3. Add the local-GPU settings — this script never touches your config.yml:
     paste the block from docs/CODING_AGENTS.md ("Settings for ~/.omp/agent/config.yml")
     into ~/.omp/agent/config.yml, or load them per run:
                      omp --config "$ROOT_DIR/services/omp/omp-club.yml"
     ⚠️ Set modelRoles either way: with none, omp picks a model on its own from every
     gateway route, and a route you can't use can win.

${STEP4}

  Optional: decode speed + prompt-cache share in the statusline:
                      cp "$ROOT_DIR/services/omp/extensions/tps-meter.ts" ~/.omp/agent/extensions/

  Always write models as club/<id> — a bare id can fuzzy-match a cloud provider.
  Scripted:  omp -p --model club/qwen3.8-27b --thinking low "..." </dev/null
EOF
if ! command -v omp >/dev/null 2>&1; then
  echo ""
  echo "  (omp is not on PATH — install it first: https://github.com/can1357/oh-my-pi)"
fi
